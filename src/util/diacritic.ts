const replaceDiacritics = (text: string): string => {
  return text
    .replace(/[^\u0000-~]/gu, (character) => DIACRITIC_EXCEPTIONS[character] ?? character)
    .normalize("NFKD")
    .replace(/\p{M}/gu, "");
};

